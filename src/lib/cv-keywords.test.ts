import assert from "node:assert/strict";
import { addCvTerm, hasCvTerm, confirmCvTerm, markOfferApplied, appliedOfferIds } from "./cv-keywords";
import { cvToText, parseCvText } from "./cv";
import type { UserData, DetectedOffer } from "./data";
const cv = parseCvText("Thomas Martin\nÉtudiant ingénieur\nthomas@example.test\nFORMATION\nÉcole électrique\nCOMPÉTENCES\nPython");
assert.equal(hasCvTerm("digital", "Git"), false);
assert.equal(hasCvTerm("C++ et MATLAB", "C++"), true);
assert.equal(hasCvTerm("Génie électrique", "genie electrique"), true);
assert.equal(addCvTerm(cv, "Python"), cv);
const added = addCvTerm(cv, "AutoCAD");
assert.equal(hasCvTerm(cvToText(added), "AutoCAD"), true);
assert.equal(hasCvTerm(cvToText(cv), "AutoCAD"), false);
const data = { profile: { skills: [] }, cvData: cv, offers: [], dossiers: {}, applications: [] } as unknown as UserData;
const offer = { id: "gmail-job", title: "Stage électrique", company: "Entreprise", keywords: ["AutoCAD"], text: "AutoCAD" } as DetectedOffer;
const updated = confirmCvTerm(data, offer, "AutoCAD");
assert.equal(updated.cvPreservedData, cv);
assert.equal(hasCvTerm(updated.dossiers![offer.id].cvText, "AutoCAD"), true);
assert.equal(updated.profile.skills[0], "AutoCAD");
const twice = confirmCvTerm(updated, offer, "AutoCAD");
assert.equal(twice.profile.skills.length, 1);
const sent = markOfferApplied(updated, offer);
assert.equal(appliedOfferIds(sent).has(offer.id), true);
assert.equal(markOfferApplied(sent, offer), sent);
assert.equal(sent.applications[0].cvText, updated.dossiers![offer.id].cvText);
const after = confirmCvTerm(sent, offer, "MATLAB");
assert.equal(after.dossiers![offer.id].cvText, sent.dossiers![offer.id].cvText, "preserve the sent CV");
assert.equal(after.applications[0].cvText, sent.applications[0].cvText);
const removed = { ...sent, applications: [] };
assert.equal(appliedOfferIds(removed).size, 0);
console.log("Compétences vérifiées : ajout aux deux CV, mots entiers, doublons, original et CV envoyé conservés, candidature liée et réversible.");
